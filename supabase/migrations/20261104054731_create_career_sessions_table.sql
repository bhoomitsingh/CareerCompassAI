/*
# Create career_sessions table

1. New Tables
- `career_sessions`
  - `id` (uuid, primary key): random identifier generated by the app and stored on the user's device.
  - `session` (jsonb, not null, default '{}'): the full saved session document (onboarding profile, assessment answers and results, saved careers, roadmap progress, compare list).
  - `created_at` (timestamptz): when the session was first saved.
  - `updated_at` (timestamptz): when the session was last saved.

2. Security
- Row level security is enabled on `career_sessions`.
- The app has no sign-in screen, so requests run as the `anon` role. Policies are granted to `anon` and `authenticated`.
- Each operation (select, insert, update) has its own policy. Deletes are not granted.
- Rows are only addressed by their random identifier; the app never lists sessions.

3. Important Notes
- No sign-in is involved. Session data is not tied to an account.
- Because there is no account, the database cannot restrict which rows a visitor may read. Anyone holding the public key could in principle list all rows. Adding sign-in would close this gap.
*/

CREATE TABLE IF NOT EXISTS career_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  session jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE career_sessions ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE ON career_sessions TO anon, authenticated;

DROP POLICY IF EXISTS "anon_select_career_sessions" ON career_sessions;
CREATE POLICY "anon_select_career_sessions" ON career_sessions FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_career_sessions" ON career_sessions;
CREATE POLICY "anon_insert_career_sessions" ON career_sessions FOR INSERT
  TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_career_sessions" ON career_sessions;
CREATE POLICY "anon_update_career_sessions" ON career_sessions FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);
